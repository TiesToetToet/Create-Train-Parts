package com.tiestoettoet.create_train_parts.foundation.render;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.WeakHashMap;

import org.jetbrains.annotations.Nullable;

import dev.engine_room.flywheel.lib.model.baked.PartialModel;
import it.unimi.dsi.fastutil.ints.Int2ObjectMap;
import it.unimi.dsi.fastutil.ints.Int2ObjectOpenHashMap;
import net.createmod.catnip.data.Iterate;
import net.createmod.catnip.render.SuperBufferFactory;
import net.createmod.catnip.render.SuperByteBuffer;
import net.createmod.catnip.render.SuperByteBufferCache;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.block.model.BakedQuad;
import net.minecraft.client.resources.model.BakedModel;
import net.minecraft.core.Direction;
import net.minecraft.util.RandomSource;
import net.minecraft.world.level.block.state.BlockState;
import net.neoforged.neoforge.client.model.BakedModelWrapper;
import net.neoforged.neoforge.client.model.data.ModelData;

/**
 * Partial models generated by build_models.py that bundle every facing / connected state / CT face variant
 * into one file. Each face's tint index holds its variant code, which is used here to split the quads again.
 */
public final class CTPartialModels {

	public static final SuperByteBufferCache.Compartment<Key> CT_PARTIAL = new SuperByteBufferCache.Compartment<>();

	private static final Map<BakedModel, Int2ObjectMap<List<BakedQuad>>> QUADS_BY_VARIANT =
		Collections.synchronizedMap(new WeakHashMap<>());

	private CTPartialModels() {
	}

	/** Must match variant_code() in build_models.py. */
	public static int variantCode(Direction facing, Enum<?> connectedState, Direction ctFace) {
		return facing.get3DDataValue() * 100 + connectedState.ordinal() * 10 + ctFace.get3DDataValue();
	}

	@Nullable
	public static SuperByteBuffer get(PartialModel partial, BlockState state, int variant) {
		BakedModel model = partial.get();
		List<BakedQuad> quads = QUADS_BY_VARIANT.computeIfAbsent(model, CTPartialModels::splitByVariant)
			.get(variant);
		if (quads == null)
			return null;
		return SuperByteBufferCache.getInstance()
			.get(CT_PARTIAL, new Key(partial, variant),
				() -> SuperBufferFactory.getInstance().createForBlock(new QuadListModel(model, quads), state));
	}

	private static Int2ObjectMap<List<BakedQuad>> splitByVariant(BakedModel model) {
		RandomSource random = RandomSource.create();
		List<BakedQuad> all = new ArrayList<>(model.getQuads(null, null, random, ModelData.EMPTY, null));
		for (Direction side : Iterate.directions)
			all.addAll(model.getQuads(null, side, random, ModelData.EMPTY, null));

		Int2ObjectMap<List<BakedQuad>> result = new Int2ObjectOpenHashMap<>();
		for (BakedQuad quad : all) {
			if (!quad.isTinted())
				continue;
			// Strip the tint index so it is not picked up as a block color
			result.computeIfAbsent(quad.getTintIndex(), k -> new ArrayList<>())
				.add(new BakedQuad(quad.getVertices(), -1, quad.getDirection(), quad.getSprite(), quad.isShade(),
					quad.hasAmbientOcclusion()));
		}
		return result;
	}

	public record Key(PartialModel partial, int variant) {
	}

	private static class QuadListModel extends BakedModelWrapper<BakedModel> {
		private final List<BakedQuad> quads;

		QuadListModel(BakedModel original, List<BakedQuad> quads) {
			super(original);
			this.quads = quads;
		}

		@Override
		public List<BakedQuad> getQuads(@Nullable BlockState state, @Nullable Direction side, RandomSource rand) {
			return side == null ? quads : List.of();
		}

		@Override
		public List<BakedQuad> getQuads(@Nullable BlockState state, @Nullable Direction side, RandomSource rand,
										ModelData data, @Nullable RenderType renderType) {
			return side == null ? quads : List.of();
		}
	}
}
